def _src(lines):
    text = "\n".join(lines)
    parts = text.split("\n")
    if len(parts) == 1:
        return [parts[0]]
    return [p + "\n" for p in parts[:-1]] + [parts[-1]]


def md(*lines):
    return {"cell_type": "markdown", "metadata": {}, "source": _src(lines)}


def code(*lines):
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": _src(lines),
    }


def pyrepr(obj, indent=0):
    """Pretty Python literal for embedding dicts/lists into a code cell."""
    pad = " " * indent
    if isinstance(obj, dict):
        if not obj:
            return "{}"
        inner = []
        for k, v in obj.items():
            inner.append(f'{pad}    {k!r}: {pyrepr(v, indent + 4)},')
        return "{\n" + "\n".join(inner) + f"\n{pad}}}"
    if isinstance(obj, list):
        if not obj:
            return "[]"
        inner = [f'{pad}    {pyrepr(v, indent + 4)},' for v in obj]
        return "[\n" + "\n".join(inner) + f"\n{pad}]"
    return repr(obj)


